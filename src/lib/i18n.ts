const WEEKDAY_EN: Record<string, string> = { Senin: "Mon", Selasa: "Tue", Rabu: "Wed", Kamis: "Thu", Jumat: "Fri", Sabtu: "Sat", Minggu: "Sun" };

// Label program yang tersusun dari pola tetap (durasi, level masuk, jadwal batch) diterjemahkan otomatis.
export function programLabelEn(label: string) {
  return label
    .replace(/Membership bulanan/i, "Monthly membership")
    .replace(/(\d+)\s*minggu/gi, (_, n) => `${n} ${n === "1" ? "week" : "weeks"}`)
    .replace(/(\d+)\s*mnt/gi, "$1 min")
    .replace(/Assessment diagnostik/i, "Diagnostic assessment")
    .replace(/Pemula/gi, "Beginner")
    .replace(/usia/gi, "age")
    .replace(/\b(Senin|Selasa|Rabu|Kamis|Jumat|Sabtu|Minggu)\b/g, (d) => WEEKDAY_EN[d])
    .replace(/\s&\s/g, " & ");
}

