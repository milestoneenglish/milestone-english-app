export type Lang = "id" | "en";

export const isLang = (v: unknown): v is Lang => v === "id" || v === "en";

/** Alamat halaman publik dalam bahasa tertentu. */
export function localePath(lang: Lang, path: string) {
  if (lang === "id") return path;
  return path === "/" ? "/en" : `/en${path}`;
}

/** Pasangan halaman dalam bahasa lain, untuk tombol ID | EN. */
export function switchPath(pathname: string, to: Lang) {
  const base = pathname === "/en" ? "/" : pathname.startsWith("/en/") ? pathname.slice(3) : pathname;
  return localePath(to, base);
}

